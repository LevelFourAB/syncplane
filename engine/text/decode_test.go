package text_test

import (
	"encoding/hex"
	"math/rand"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	"github.com/levelfourab/syncplane/engine/text"
)

// Corrupt and truncated bytes. A decoder that accepts damaged bytes as a
// different, well-formed document turns transport or storage damage into
// silent text corruption; one that disagrees with the other language's
// decoder stores rows only one side can read.

// damagedPath holds generated damaged documents with Go's verdict on each,
// shared with client/test/unit/text-laws.test.ts. Run the suite with -update
// to rewrite it after a change to the encoding.
const damagedPath = "../../testdata/text/damaged.json"

type decodeCase struct {
	Input string `json:"input"`           // hex
	Doc   string `json:"doc,omitempty"`   // hex of the canonical re-encoding when accepted
	Error string `json:"error,omitempty"` // Go's message when refused
}

type damagedFile struct {
	Comment string       `json:"comment"`
	Cases   []decodeCase `json:"cases"`
}

func decodeVerdict(b []byte) decodeCase {
	c := decodeCase{Input: hex.EncodeToString(b)}
	d, err := text.Decode(b, "")
	if err != nil {
		c.Error = err.Error()
		return c
	}
	c.Doc = hex.EncodeToString(d.Encode())
	return c
}

// sampleDocs returns n encoded documents from random histories of 10 to
// maxRounds rounds.
func sampleDocs(rng *rand.Rand, n, maxRounds int) [][]byte {
	GinkgoHelper()
	var out [][]byte
	for i := 0; i < n; i++ {
		c := runLawCase(int64(70000+i), 10+rng.Intn(maxRounds-9))
		b, err := hex.DecodeString(c.Merged)
		Expect(err).NotTo(HaveOccurred())
		out = append(out, b)
	}
	return out
}

// damage returns a copy of doc with one bit flipped, or one byte replaced,
// deleted or duplicated.
func damage(rng *rand.Rand, doc []byte) []byte {
	b := append([]byte(nil), doc...)
	switch rng.Intn(4) {
	case 0:
		i := rng.Intn(len(b))
		b[i] ^= 1 << rng.Intn(8)
	case 1:
		b[rng.Intn(len(b))] = byte(rng.Intn(256))
	case 2:
		i := rng.Intn(len(b))
		b = append(b[:i], b[i+1:]...)
	default:
		i := rng.Intn(len(b))
		b = append(b[:i+1], b[i:]...)
	}
	return b
}

var _ = Describe("Decoding damaged bytes", func() {
	It("refuses every strict prefix of a document", func() {
		rng := rand.New(rand.NewSource(31337))
		for _, doc := range sampleDocs(rng, 30, 64) {
			// An empty input is the empty document by design, so n starts at 1.
			for n := 1; n < len(doc); n++ {
				_, err := text.Decode(doc[:n], "")
				Expect(err).To(HaveOccurred(), "prefix %d of %d decoded: %x", n, len(doc), doc[:n])
			}
		}
	})

	It("re-encodes accepted damage to canonical bytes that decode again", func() {
		rng := rand.New(rand.NewSource(271828))
		for _, doc := range sampleDocs(rng, 30, 64) {
			for k := 0; k < 60; k++ {
				b := damage(rng, doc)
				v := decodeVerdict(b)
				if v.Doc == "" {
					continue
				}
				re, _ := hex.DecodeString(v.Doc)
				again := decodeVerdict(re)
				Expect(again.Error).To(BeEmpty(), "accepted damage re-encodes to bytes Decode refuses: %x", b)
				Expect(again.Doc).To(Equal(v.Doc))
			}
		}
	})

	It("gives the verdicts shared with the TS harness", func() {
		if *update {
			f := damagedFile{Comment: "Generated by engine/text/decode_test.go; rewrite with " +
				"`go test ./engine/text -update`. Each case is a damaged document (input) with " +
				"the canonical re-encoding Go accepts it as (doc), or the message Go refuses it " +
				"with (error). client/test/unit/text-laws.test.ts must accept and refuse the " +
				"same inputs, with the same doc; its messages may differ."}
			rng := rand.New(rand.NewSource(161803))
			for _, doc := range sampleDocs(rng, 8, 24) {
				for k := 0; k < 25; k++ {
					f.Cases = append(f.Cases, decodeVerdict(damage(rng, doc)))
				}
			}
			writeVectorFile(damagedPath, f)
		}
		var f damagedFile
		readVectorFile(damagedPath, &f)
		Expect(f.Cases).NotTo(BeEmpty())
		for _, want := range f.Cases {
			b, err := hex.DecodeString(want.Input)
			Expect(err).NotTo(HaveOccurred())
			Expect(decodeVerdict(b)).To(Equal(want))
		}
	})
})
