// What a one-hop semi-join costs, split into the two halves that can each grow
// without the other noticing.
//
// A `matches` is answered in two phases (see
// docs/explanation/relational-queries.md): a PRE-PASS runs the inner condition
// over the target entity and collects the matching keys K, then the node is
// REWRITTEN to a membership test on the stored ref stubs and the query runs
// row-local. The benchmarks below price each half against the whole, over the
// bench corpus: `comment` rows are the outer entity and `issue` the target,
// with an inner predicate that the target's by_state_priority index serves and
// that roughly 2% of the entity matches.
//
// Both halves have an asymptote worth keeping an eye on. The pre-pass is a
// query, so it is O(matches) with an index and O(target entity) without one —
// which is why RelPrePassAsQuery prices the same inner predicate as an
// ordinary query and the difference to RelWhole is what the rewrite adds. The
// membership test is O(|K|) per candidate row if it is compared value by
// value, which is what RelMembership sweeps: the K column must stay FLAT.
//
// The shape to expect (Apple M2 Pro, tier=l — 50k issues, 30k comments):
//
//	                      time      alloc
//	RelWhole              87 ms      50 MB
//	RelPrePassAsQuery     29 ms     5.5 MB
//	RelMembership K=1    118 µs      12 KB
//	RelMembership K=16   711 µs      65 KB
//	RelMembership K=128   60 ms      44 MB
//	RelMembership K=1024  55 ms      44 MB
//
// The absolute numbers will drift; two shapes are the point. K=128 and K=1024
// cost the same — a sloping membership column means the hash set stopped being
// built (see inSetThreshold). And the step up at K=128 is the index walk
// exhausting MaxIndexScanCandidates and falling back to the scan, which the
// allocation column shows plainly: membership is what sits on top of a full
// pass over the outer entity from there on.
//
// Seeding a tier is minutes of work, so every benchmark here shares one server
// per tier, and the seeded database is cached between RUNS as well — under
// benchapp's GeneratorVersion, so a corpus generated by an older version is
// regenerated rather than silently reused.
var relFixtures sync.Map

type relFixture struct {
	srv *server.Server
	ws  string
}

func relBenchServer(b *testing.B, tierName string) *relFixture {
	b.Helper()
	if v, ok := relFixtures.Load(tierName); ok {
		return v.(*relFixture)
	}
	tier := benchapp.Tiers[tierName]
	ctx := context.Background()
	ws := benchapp.WorkspaceID(tier.Name)
	// A DIRECTORY per corpus, renamed into place once it is whole: SQLite
	// keeps -wal and -shm beside the database, so moving the file alone would
	// publish a corpus missing whatever the write-ahead log still held.
	dir := filepath.Join(os.TempDir(),
		fmt.Sprintf("syncplane-relbench-v%d-%s", benchapp.GeneratorVersion, tier.Name))
	if _, err := os.Stat(dir); err != nil {
		staging := dir + ".seeding"
		if err := os.RemoveAll(staging); err != nil {
			b.Fatal(err)
		}
		if err := os.MkdirAll(staging, 0o755); err != nil {
			b.Fatal(err)
		}
		if err := seedRelCorpus(ctx, filepath.Join(staging, corpusDB), tier, ws); err != nil {
			b.Fatal(err)
		}
		if err := os.Rename(staging, dir); err != nil {
			b.Fatal(err)
		}
	}

	store, err := sqlitestore.Open(filepath.Join(dir, corpusDB))
	if err != nil {
		b.Fatal(err)
	}
	srv, err := server.New(store, benchapp.Options()...)
	if err != nil {
		b.Fatal(err)
	}
	f := &relFixture{srv: srv, ws: ws}
	relFixtures.Store(tierName, f)
	return f
}

const corpusDB = "corpus.db"

func seedRelCorpus(ctx context.Context, path string, tier benchapp.Tier, ws string) error {
	store, err := sqlitestore.Open(path)
	if err != nil {
		return err
	}
	defer func() { _ = store.Close() }()
	srv, err := server.New(store, benchapp.Options()...)
	if err != nil {
		return err
	}
	defer func() { _ = srv.Close() }()
	if _, err := benchapp.Seed(ctx, srv, ws, tier, 1, nil); err != nil {
		return err
	}
	return srv.BuildIndexes(ctx, ws)
}

// reviewIssues is the inner predicate throughout: selective (1/7 x 1/5 of the
// issue entity) and served by the by_state_priority index.
func reviewIssues() *syncplanev1.Condition {
	return query.And(query.Eq("state", "review"), query.Eq("priority", int32(4)))
}

func (f *relFixture) run(b *testing.B, entity string, pred *syncplanev1.Condition) {
	b.Helper()
	ctx := context.Background()
	req := connect.NewRequest(&syncplanev1.QueryRequest{
		WorkspaceId: f.ws, Entity: entity, Predicate: pred, Limit: 20,
	})
	// A benchmark measuring an empty result would measure nothing.
	resp, err := f.srv.Query(ctx, req)
	if err != nil {
		b.Fatal(err)
	}
	if len(resp.Msg.GetRows()) == 0 {
		b.Fatalf("query on %s matched no rows", entity)
	}
	b.ReportAllocs()
	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		if _, err := f.srv.Query(ctx, req); err != nil {
			b.Fatal(err)
		}
	}
}

// membershipKeys is the key set the inner predicate selects — the K a
// `matches` would produce — with the keys some comment actually references
// FIRST. Comments cluster on a fraction of the issues, so a K cut from the
// front of an arbitrary order would name issues no comment points at, and the
// sweep would time an empty result at its small sizes.
func (f *relFixture) membershipKeys(b *testing.B) []string {
	b.Helper()
	ctx := context.Background()
	matching, err := f.srv.Query(ctx, connect.NewRequest(&syncplanev1.QueryRequest{
		WorkspaceId: f.ws, Entity: "issue", Predicate: reviewIssues(),
	}))
	if err != nil {
		b.Fatal(err)
	}
	comments, err := f.srv.Query(ctx, connect.NewRequest(&syncplanev1.QueryRequest{
		WorkspaceId: f.ws, Entity: "comment",
	}))
	if err != nil {
		b.Fatal(err)
	}
	referenced := make(map[string]struct{})
	for _, r := range comments.Msg.GetRows() {
		var msg benchv1.Comment
		if err := proto.Unmarshal(r.GetValue(), &msg); err != nil {
			b.Fatal(err)
		}
		referenced[msg.GetIssue().GetId()] = struct{}{}
	}
	var hot, cold []string
	for _, r := range matching.Msg.GetRows() {
		var msg benchv1.Issue
		if err := proto.Unmarshal(r.GetValue(), &msg); err != nil {
			b.Fatal(err)
		}
		if _, ok := referenced[msg.GetId()]; ok {
			hot = append(hot, msg.GetId())
		} else {
			cold = append(cold, msg.GetId())
		}
	}
	if len(hot) == 0 {
		b.Fatal("no matching issue is referenced by a comment; the corpus or the predicate moved")
	}
	return append(hot, cold...)
}

// The whole two-phase rewrite: the pre-pass plus the membership query it
// collapses to.
func BenchmarkRelWhole(b *testing.B) {
	for _, tier := range []string{"m", "l"} {
		b.Run("tier="+tier, func(b *testing.B) {
			relBenchServer(b, tier).run(b, "comment", query.Rel("issue", reviewIssues()))
		})
	}
}

// The pre-pass alone, priced as the query it is.
func BenchmarkRelPrePassAsQuery(b *testing.B) {
	for _, tier := range []string{"m", "l"} {
		b.Run("tier="+tier, func(b *testing.B) {
			relBenchServer(b, tier).run(b, "issue", reviewIssues())
		})
	}
}

// The membership half alone, swept over |K|. See the header: this column has
// to stay flat.
func BenchmarkRelMembership(b *testing.B) {
	for _, tier := range []string{"m", "l"} {
		f := relBenchServer(b, tier)
		all := f.membershipKeys(b)
		for _, n := range []int{1, 16, 128, 1024} {
			if n > len(all) {
				continue
			}
			keys := all[:n]
			b.Run(fmt.Sprintf("tier=%s/K=%d", tier, n), func(b *testing.B) {
				f.run(b, "comment", query.In("issue.id", keys...))
			})
		}
	}
}
