package search_test

import (
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"
	"unicode"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"golang.org/x/text/cases"
	"golang.org/x/text/unicode/norm"

	"github.com/levelfourab/syncplane/engine/search"
)

var update = flag.Bool("update", false, "rewrite the generated Unicode table of the TS analyzer")

// assignedTablePath is the TS analyzer's copy of the code points
// search.UnicodeVersion assigns. The TS side masks every other code point
// before it normalizes, because its runtime tables can be newer than these.
const assignedTablePath = "../../client/src/search/assigned.ts"

var _ = Describe("pinned Unicode version", func() {
	// The analyzer reads its letter classes, NFKC and case mappings from these
	// three tables. A toolchain or golang.org/x/text upgrade that moves any of
	// them changes the terms of text in newly assigned scripts, and the TS
	// analyzer stays on search.UnicodeVersion. Before such an upgrade, mask
	// the code points that search.UnicodeVersion does not assign on this side
	// too, or move the pin on both sides and fold it into both search spec
	// hashes so stored indexes rebuild.
	It("matches the tables the analyzer reads", func() {
		Expect(unicode.Version).To(Equal(search.UnicodeVersion), "unicode")
		Expect(norm.Version).To(Equal(search.UnicodeVersion), "golang.org/x/text/unicode/norm")
		Expect(cases.UnicodeVersion).To(Equal(search.UnicodeVersion), "golang.org/x/text/cases")
	})

	It("is the table the TS analyzer masks with", func() {
		want := assignedTableSource()
		if *update {
			Expect(os.WriteFile(assignedTablePath, []byte(want), 0o644)).To(Succeed())
		}
		got, err := os.ReadFile(assignedTablePath)
		Expect(err).NotTo(HaveOccurred())
		Expect(string(got)).To(Equal(want), "run go test ./engine/search -update")
	})
})

// assignedTableSource renders the TS module that lists the code points the
// running Go tables assign, as base-36 lengths of alternating assigned and
// unassigned runs from U+0000. The final unassigned run is left out.
func assignedTableSource() string {
	var runs []string
	start, in := rune(0), true
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if a := !unicode.Is(unicode.Cn, r); a != in {
			runs = append(runs, strconv.FormatInt(int64(r-start), 36))
			start, in = r, a
		}
	}
	if in {
		runs = append(runs, strconv.FormatInt(int64(unicode.MaxRune+1-start), 36))
	}

	var b strings.Builder
	b.WriteString("// Code generated by `go test ./engine/search -update`. DO NOT EDIT.\n\n")
	b.WriteString("/** The Unicode version whose code point assignments the analyzer follows. */\n")
	fmt.Fprintf(&b, "export const UNICODE_VERSION = '%s';\n\n", unicode.Version)
	b.WriteString("/**\n")
	b.WriteString(" * The code points UNICODE_VERSION assigns (every general category but Cn),\n")
	b.WriteString(" * as base-36 lengths of alternating assigned and unassigned runs from\n")
	b.WriteString(" * U+0000. The code points after the last run are unassigned.\n")
	b.WriteString(" */\n")
	b.WriteString("export const ASSIGNED_RUNS = `\n")
	line := ""
	for i, r := range runs {
		item := r
		if i < len(runs)-1 {
			item += ","
		}
		if len(line)+len(item) > 79 {
			b.WriteString(line + "\n")
			line = ""
		}
		line += item
	}
	b.WriteString(line + "\n`;\n")
	return b.String()
}
